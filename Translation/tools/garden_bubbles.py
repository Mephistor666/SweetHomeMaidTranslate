def build(src_root: pathlib.Path, out_root: pathlib.Path, dry: bool) -> int:
    missing: dict[str, list[str]] = {}
    total = replaced = 0
    for f in sorted(src_root.glob("*.json")):
        data = json.loads(f.read_text(encoding="utf-8-sig"))
        name = data[5][0][1]
        obj = data[5][0][2]

        def walk(node):
            nonlocal total, replaced
            if isinstance(node, dict):
                for k, v in list(node.items()):
                    if k == "message" and isinstance(v, str):
                        total += 1
                        if v in TABLE:
                            if node[k] != TABLE[v]:
                                replaced += 1
                            node[k] = TABLE[v]
                        else:
                            missing.setdefault(name, []).append(v)
                    else:
                        walk(v)
            elif isinstance(node, list):
                for v in node:
                    walk(v)

        walk(obj)
        if dry:
            continue
        raw = f.read_text(encoding="utf-8-sig")
        style = st.detect_style(raw)
        has_bom = f.read_bytes().startswith(b"\xef\xbb\xbf")
        out = out_root / (f.stem + "_cn.json")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_bytes(st.dump_like(data, style, has_bom))

    print(f"message 共 {total} 处，套用译文 {replaced} 处")
    if missing:
        print(f"[警告] 有 {sum(len(v) for v in missing.values())} 处没在对照表里：")
        for k, vals in missing.items():
            for v in sorted(set(vals))[:20]:
                print(f"   {k}: {v}")
    else:
        print("对照表覆盖完整 ✓")
    return len(missing)


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    p = argparse.ArgumentParser(description="主页角色互动气泡文本翻译")
    p.add_argument("--root", help="仓库根目录，默认自动定位")
    p.add_argument("--src", default="Resources/Garden", help="原文目录")
    p.add_argument("--out", default="Translation/Resources/Garden", help="成品目录")
    p.add_argument("--check", action="store_true", help="只检查覆盖，不写盘")
    args = p.parse_args()

    root = pathlib.Path(args.root).resolve() if args.root else pathlib.Path(__file__).resolve().parents[2]
    src = (root / args.src).resolve()
    out = (root / args.out).resolve()
    if not src.is_dir():
        raise SystemExit(f"[错误] 找不到 {src}")
    n = build(src, out, args.check)
    if not args.check:
        print(f"已写出到 {out}")
    sys.exit(1 if n else 0)


if __name__ == "__main__":
    main()
